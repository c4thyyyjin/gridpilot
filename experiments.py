"""Reproduces every number and figure in the report.   Usage:  python experiments.py [--quick]

Outputs: results/*.csv, results/RESULTS.md, figures/*.png
Methods compared (all scored by evaluate.py on ACTUAL values):
  baseline    - run jobs ASAP (earliest-deadline-first), no battery, sees the ACTUAL load each hour.
                THE reference for every 'gain vs baseline' number (same information as MPC).
  baseline-fc - same, but plans capacity on forecasts; secondary row in the headline table only
  open-loop  - LP planned once on forecasts
  MPC        - LP re-solved every hour with observed values   <- our method
  oracle     - LP with perfect knowledge of the future        <- lower bound
"""
