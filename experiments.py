from reporting import METRICS, aggregate, feasible_gain, paired_comparisons, run_stress


@contextmanager
def preserved_config():
    """Restore all config constants on success or failure, including mutable values."""
    saved = {k: copy.deepcopy(v) for k, v in vars(C).items() if k.isupper()}
    try:
        yield
    finally:
        for name in list(vars(C)):
            if name.isupper() and name not in saved:
                delattr(C, name)
        for name, value in saved.items():
            current = getattr(C, name, None)
            if isinstance(value, dict) and isinstance(current, dict):
                current.clear()
                current.update(copy.deepcopy(value))
            elif isinstance(value, list) and isinstance(current, list):
                current[:] = copy.deepcopy(value)
            else:
                setattr(C, name, copy.deepcopy(value))


def run_experiments(quick=False, output_dir=".", config_overrides=None):
    """Generate outputs in output_dir without changing cwd or retaining config changes."""
    import matplotlib
    if "matplotlib.pyplot" not in sys.modules:
        matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    existing_figures = set(plt.get_fignums())
    with preserved_config(), plt.rc_context():
        try:
            if config_overrides is not None:
                if not isinstance(config_overrides, dict):
                    raise ValueError("config overrides must be a JSON object/dict")
                for name, value in config_overrides.items():
                    if not name.isupper() or not hasattr(C, name):
                        raise ValueError(f"unknown config constant: {name}")
                    original = getattr(C, name)
                    if isinstance(original, tuple):
                        value = tuple(value)
                    if isinstance(original, dict) and original and all(isinstance(k, int) for k in original):
                        value = {int(k): v for k, v in value.items()}
                    setattr(C, name, copy.deepcopy(value))
            return _run_experiments(quick, Path(output_dir).expanduser().resolve())
        finally:
            for number in set(plt.get_fignums()) - existing_figures:
                plt.close(number)


def _run_experiments(quick, output_dir):
    import matplotlib.pyplot as plt
    from plotting import plot_pareto
    from economics import grid_cap_summary, economics_tables

    results, figures = output_dir / "results", output_dir / "figures"
    results.mkdir(parents=True, exist_ok=True)
    figures.mkdir(parents=True, exist_ok=True)
    LAM = C.LAMBDA_DEFAULT
    GL = C.GRID_IMPORT_LIMIT_MW
    SEEDS = list(range(3 if quick else 5))
    COL = {"baseline": "#888888", "open-loop": "#e0a030", "MPC": "#2a7ab9", "oracle": "#2a9d5c"}
    plt.rcParams.update({"figure.dpi": 130, "axes.grid": True, "grid.alpha": .25, "axes.spines.top": False, "axes.spines.right": False})
    RUNS, BATCHES, PAIRED, SEED_PAIRS = [], [], [], []
    _last_section_batch = 0
    md = ["# Results (auto-generated by experiments.py)\n", f"seeds={SEEDS}, lambda={LAM} CNY/tCO2, grid limit={GL} MW\n",
          "Savings are shown only when every run of both methods is feasible. Blank gains mean ineligible, not zero savings. "
          "Penalized objectives quantify service loss and overflow; feasibility takes precedence. "
          "See run_metrics.csv for individual outcomes and feasibility.csv for worst-case diagnostics. "
          "Paired 95% Student-t intervals use within-seed savings (baseline minus method), with n-1 degrees of freedom; "
          "percentage intervals estimate the mean per-seed percentage, not the ratio of mean costs. "
          "With only three/five synthetic seeds these are approximate, pointwise intervals, not real-site guarantees "
          "or simultaneous significance tests. Infeasible pairs are retained and disqualify the whole comparison.\n"]


    def run(sc, method, lam=LAM, gl=GL):
        if method == "baseline": return baseline_observed(sc)          # fair: sees the actual current-hour load
        if method == "baseline-fc": return baseline_forecast_planned(sc)   # plans capacity on forecasts (weaker, secondary row)
        if method == "open-loop": return open_loop_schedule(sc, lam, gl)
        if method == "MPC": return mpc_schedule(sc, lam, gl)
        if method == "oracle": return open_loop_schedule(sc, lam, gl, use_forecast=False)


    def avg(methods, err=0.3, lam=LAM, gl=GL, scen_fn=None, seeds=SEEDS):
        """Mean metrics per method over seeds."""
        out = {}
        batch = len(BATCHES)
        start_run = len(RUNS)
        for m in methods:
            rows = []
            for s in seeds:
                sc = make_scenario(s, forecast_error=err)
                if scen_fn: sc = scen_fn(sc)
                sch = run(sc, m, lam, gl)
                r = evaluate(sc, sch, lam, grid_limit=gl)
                row = {k: r[k] for k in METRICS + ["status", "feasible"]}
                rows.append(row)
                RUNS.append({"batch": batch, "method": m, "seed": s, "forecast_error": err,
                             "lambda": lam, "grid_limit_mw": gl, "grid_limit_label": "uncapped" if gl is None else f"{gl:g} MW",
                             "horizon_hours": sc.T * C.DT_H, "battery_mwh": C.BATT_ENERGY_MWH,
                             "battery_power_mw": C.BATT_POWER_MW,
                             "inference_share": C.SHARE_INFERENCE, "job_slack": str(C.JOB_SLACK),
                             "carbon_swing": C.GRID_CO2_SWING, "price_levels": str(C.PRICE_LEVELS),
                             "fallback_hour_indices": str(sch.info.get("fallback_hours", [])), **row})
            out[m] = aggregate(rows)
        for method, metrics in out.items():
            BATCHES.append({"batch": batch, "method": method, "forecast_error": err,
                            "lambda": lam, "grid_limit_mw": gl, "grid_limit_label": "uncapped" if gl is None else f"{gl:g} MW", **metrics})
        paired, seed_pairs = paired_comparisons(RUNS[start_run:])
        PAIRED.extend(paired.to_dict("records"))
        SEED_PAIRS.extend(seed_pairs.to_dict("records"))
        return pd.DataFrame(out).T


    def gain(df, col="objective"):
        return feasible_gain(df, col)


    def section(title, df):
        nonlocal _last_section_batch
        md.append(f"\n## {title}\n"); md.append(df.round(2).to_markdown() + "\n")
        diagnostics = pd.DataFrame(BATCHES[_last_section_batch:])
        if not diagnostics.empty:
            batch_ids = set(diagnostics.batch)
            for record in PAIRED + SEED_PAIRS:
                if record["batch"] in batch_ids:
                    record["section"] = title
            for record in BATCHES[_last_section_batch:]:
                record["section"] = title
            columns = ["batch", "method", "status", "feasible_runs", "runs", "penalized_objective",
                       "max_unmet_job_mwh", "max_grid_overflow_mwh", "max_capacity_violation_hours",
                       "max_grid_limit_violation_hours", "max_sla_violations", "max_battery_violation",
                       "max_inference_overload_hours", "max_fallback_hours"]
            md.append("\nFeasibility diagnostics (maxima are across seeds; fallback hours and violation counts are worst-case per run):\n")
            md.append(diagnostics[columns].round(3).to_markdown(index=False) + "\n")
            paired = pd.DataFrame([r for r in PAIRED if r["batch"] in batch_ids])
            md.append("\nPaired 95% intervals across seeds (blank estimates are ineligible):\n")
            cols = ["batch", "method", "metric", "n_pairs", "n_feasible_pairs", "status",
                    "gain_pct_mean", "gain_pct_ci_low", "gain_pct_ci_high"]
            md.append(paired[cols].round(3).to_markdown(index=False) + "\n")
        _last_section_batch = len(BATCHES)


    # ---------------------------------------------------------------- 1. headline table
    print("1/10 headline")
    H = avg(["baseline", "baseline-fc", "open-loop", "MPC", "oracle"], err=0.3)
    H["objective_gain_%"] = gain(H); H["cost_gain_%"] = gain(H, "cost_cny"); H["co2_gain_%"] = gain(H, "co2_t")
    H.to_csv(results / "headline.csv"); section("1. Headline (forecast error 0.3)", H)

    # ---------------------------------------------------------------- 2. lambda Pareto
    print("2/10 lambda sweep")
    lams = C.LAMBDA_SWEEP if not quick else [0, 100, 1000, 5000]
    rows = []
    for lam in lams:
        b = r = avg(["baseline", "MPC"], lam=lam)
        rows.append({"lambda": lam, "cost": r.loc["MPC", "cost_cny"] if r.loc["MPC", "all_feasible"] else np.nan, "co2": r.loc["MPC", "co2_t"] if r.loc["MPC", "all_feasible"] else np.nan, "green_%": r.loc["MPC", "green_share_pct"],
                     "base_cost": b.loc["baseline", "cost_cny"] if b.loc["baseline", "all_feasible"] else np.nan, "base_co2": b.loc["baseline", "co2_t"] if b.loc["baseline", "all_feasible"] else np.nan})
    P = pd.DataFrame(rows); P.to_csv(results / "pareto.csv", index=False); section("2. Cost vs CO2 (lambda sweep, MPC)", P)
    fig, ax = plot_pareto(P, figures / "pareto.png", color=COL["MPC"], baseline_color=COL["baseline"])
    plt.close(fig)

    # ---------------------------------------------------------------- 3. forecast error curve
    print("3/10 forecast error")
    errs = [0, .2, .4, .6, .8, 1.0] if not quick else [0, .4, .8]
    rows = []
    for e in errs:
        d = avg(["baseline", "open-loop", "MPC", "oracle"], err=e); g = gain(d)
        rows.append({"error": e, **{f"{m}_gain_%": g[m] for m in ("open-loop", "MPC", "oracle")},
                     "open-loop_gridV_h": d.loc["open-loop", "grid_limit_violation_hours"], "open-loop_capV_h": d.loc["open-loop", "capacity_violation_hours"],
                     "MPC_gridV_h": d.loc["MPC", "grid_limit_violation_hours"], "MPC_capV_h": d.loc["MPC", "capacity_violation_hours"],
                     "MPC_sla": d.loc["MPC", "sla_violations"]})
    F = pd.DataFrame(rows); F.to_csv(results / "forecast_error.csv", index=False); section("3. Forecast error", F)
    fig, ax = plt.subplots(1, 2, figsize=(10, 4))
    for m in ("open-loop", "MPC", "oracle"): ax[0].plot(F.error, F[f"{m}_gain_%"], "o-", color=COL[m], label=m)
    ax[0].set_xlabel("forecast error (relative std of noise)"); ax[0].set_ylabel("objective gain vs baseline (%)"); ax[0].legend(); ax[0].set_title("Savings for feasible comparisons")
    ax[1].plot(F.error, F["open-loop_capV_h"] + F["open-loop_gridV_h"], "o-", color=COL["open-loop"], label="open-loop")
    ax[1].plot(F.error, F["MPC_capV_h"] + F["MPC_gridV_h"], "o-", color=COL["MPC"], label="MPC")
    ax[1].set_xlabel("forecast error"); ax[1].set_ylabel("capacity + grid violation-hours"); ax[1].legend(); ax[1].set_title("Observed capacity and grid violations")
    fig.tight_layout(); fig.savefig(figures / "forecast_error.png"); plt.close(fig)

    # ---------------------------------------------------------------- 4. battery size
    print("4/10 battery")
    battery_start = len(RUNS)
    saved = (C.BATT_ENERGY_MWH, C.BATT_POWER_MW)
    rows = []
    try:
        for e_mwh in ([0, 10, 20, 40, 80] if not quick else [0, 20, 80]):
            C.BATT_ENERGY_MWH, C.BATT_POWER_MW = float(e_mwh), e_mwh / 2.0   # 2-hour battery
            d = avg(["baseline", "MPC"], err=0.3)
            rows.append({"battery_MWh": e_mwh, "MPC_cost": d.loc["MPC", "cost_cny"], "MPC_co2": d.loc["MPC", "co2_t"], "MPC_curtailed": d.loc["MPC", "curtailed_mwh"],
                         "objective_gain_%": gain(d)["MPC"]})
    finally:
        C.BATT_ENERGY_MWH, C.BATT_POWER_MW = saved
    battery_runs = [dict(r) for r in RUNS[battery_start:]]
    B = pd.DataFrame(rows); B["extra_gain_per_10MWh"] = B["objective_gain_%"].diff() / B["battery_MWh"].diff() * 10
    B.to_csv(results / "battery.csv", index=False); section("4. Battery size (2-hour battery); 0 MWh = job shifting only", B)
    md.append("NOTE: gains at every battery size include the effect of flexible job shifting. "
              "The 0 MWh row is MPC with no battery; the incremental effect of storage is the "
              "difference between that row and the larger sizes. The chart plots total gain, "
              "not the storage-only increment.\n")
    fig, ax = plt.subplots(figsize=(6, 4))
    ax.plot(B.battery_MWh, B["objective_gain_%"], "o-", color=COL["MPC"])
    ax.set_xlabel("battery energy (MWh)"); ax.set_ylabel("objective gain vs baseline (%)"); ax.set_title("Total gain (job shifting + storage) vs observed-demand baseline")
    fig.tight_layout(); fig.savefig(figures / "battery.png"); plt.close(fig)

    # ---------------------------------------------------------------- 5. where do savings come from / flat tariff
    print("5/10 flat tariff")
    flat = lambda sc: (setattr(sc, "price", np.full(sc.T, float(sc.price.mean()))) or sc)
    d_tou = avg(["baseline", "MPC"], err=0.3)
    d_flat = avg(["baseline", "MPC"], err=0.3, scen_fn=flat)
    Fl = pd.DataFrame({"TOU tariff": [gain(d_tou)["MPC"], gain(d_tou, "cost_cny")["MPC"], gain(d_tou, "co2_t")["MPC"]],
                       "flat tariff (same mean price)": [gain(d_flat)["MPC"], gain(d_flat, "cost_cny")["MPC"], gain(d_flat, "co2_t")["MPC"]]},
                      index=["objective gain %", "cost gain %", "CO2 gain %"])
    Fl.to_csv(results / "flat_tariff.csv"); section("5. Is the gain just price arbitrage? (flat tariff test)", Fl)

    # ---------------------------------------------------------------- 6. assumption stress tests
    print("6/10 assumptions")
    rows = []
    def stress(name, setup, teardown):
        d = run_stress(setup, lambda: avg(["baseline", "MPC"], err=0.3), teardown)
        rows.append({"assumption changed": name, "MPC objective gain %": gain(d)["MPC"], "SLA violations": d.loc["MPC", "sla_violations"]})
    orig = dict(sh=(C.SHARE_INFERENCE, C.SHARE_TRAINING, C.SHARE_BATCH), sl=C.JOB_SLACK, co2=C.GRID_CO2_SWING, pl=dict(C.PRICE_LEVELS))
    def reset():
        C.SHARE_INFERENCE, C.SHARE_TRAINING, C.SHARE_BATCH = orig["sh"]; C.JOB_SLACK = orig["sl"]; C.GRID_CO2_SWING = orig["co2"]
        C.PRICE_LEVELS.update(orig["pl"])
    stress("base case", lambda: None, reset)
    stress("less flexible work: inference 60 / training 25 / batch 15 %", lambda: setattr(C, "SHARE_INFERENCE", .60) or setattr(C, "SHARE_TRAINING", .25) or setattr(C, "SHARE_BATCH", .15), reset)
    stress("more flexible work: inference 20 / training 55 / batch 25 %", lambda: setattr(C, "SHARE_INFERENCE", .20) or setattr(C, "SHARE_TRAINING", .55) or setattr(C, "SHARE_BATCH", .25), reset)
    stress("tighter deadlines (jobs need 70-90 % of their window)", lambda: setattr(C, "JOB_SLACK", (.70, .90)), reset)
    stress("looser deadlines (jobs need 20-35 % of their window)", lambda: setattr(C, "JOB_SLACK", (.20, .35)), reset)
    stress("grid carbon constant (no hourly swing)", lambda: setattr(C, "GRID_CO2_SWING", 0.0), reset)
    stress("price spread halved (peak/critical/valley pulled toward flat)", lambda: C.PRICE_LEVELS.update({k: (v + .687) / 2 for k, v in orig["pl"].items()}), reset)
    S = pd.DataFrame(rows); S.to_csv(results / "assumption_stress.csv", index=False); section("6. If our assumptions are wrong", S)
    fig, ax = plt.subplots(figsize=(8, 4))
    values = S["MPC objective gain %"][::-1].to_numpy(float)
    labels = S["assumption changed"][::-1].to_list()
    valid = np.isfinite(values)
    colors = [COL["MPC"] if v else "#cccccc" for v in valid]
    bars = ax.barh(labels, np.where(valid, values, 0), color=colors)
    for bar, v, lab in zip(bars, valid, labels):
        if not v:
            ax.text(0.02, bar.get_y() + bar.get_height() / 2, "ineligible",
                    va="center", ha="left", fontsize=8, fontstyle="italic", color="#888888",
                    transform=ax.get_yaxis_transform())
    ax.set_xlabel("MPC objective gain vs baseline (%)"); ax.set_title("Sensitivity to workload and\nenergy assumptions")
    fig.tight_layout(); fig.savefig(figures / "assumption_stress.png"); plt.close(fig)

    # ---------------------------------------------------------------- 7. biased forecasts (failure mode)
    print("7/10 biased forecast")
    rows = []
    for bias in (-.3, 0, .3):
        def biased(sc, b=bias):
            sc.solar_act = sc.solar_fc * (1 - b); sc.wind_act = sc.wind_fc * (1 - b); return sc   # b>0: forecasts too optimistic
        d = avg(["baseline", "open-loop", "MPC"], err=0.0, scen_fn=biased)
        rows.append({"forecast bias (green)": f"{bias:+.0%}", "open-loop gain %": gain(d)["open-loop"], "MPC gain %": gain(d)["MPC"],
                     "MPC curtailed MWh": d.loc["MPC", "curtailed_mwh"], "MPC grid-limit viol. h": d.loc["MPC", "grid_limit_violation_hours"]})
    Bi = pd.DataFrame(rows); Bi.to_csv(results / "bias.csv", index=False); section("7. Systematically biased green forecast (+ = too optimistic)", Bi)

    # ---------------------------------------------------------------- 8. schedule picture
    print("8/10 schedule plot")
    sc = make_scenario(42, forecast_error=0.3)
    fig, axes = plt.subplots(3, 1, figsize=(11, 8.5), sharex=True, gridspec_kw={"height_ratios": [3, 3, 1.6]})
    t = np.arange(sc.T)
    for ax, (name, sch) in zip(axes[:2], (("Baseline: run everything as soon as it arrives", baseline_observed(sc)), ("MPC: shift flexible work to green / cheap hours", mpc_schedule(sc, LAM, GL)))):
        tr = sum(sch.job_power[k] for k, j in enumerate(sc.jobs) if j.kind == "training")
        ba = sum(sch.job_power[k] for k, j in enumerate(sc.jobs) if j.kind == "batch")
        ax.stackplot(t, sc.inference_act * C.PUE, tr * C.PUE, ba * C.PUE, labels=["inference (fixed)", "training", "batch"], colors=["#b0b7c3", "#2a7ab9", "#e0a030"], step="post")
        ax.step(t, sc.green_act, where="post", color="#2a9d5c", lw=2, label="green supply (actual)")
        ax.set_ylabel("facility MW"); ax.set_title(name, fontsize=10, loc="left"); ax.set_ylim(0, 30)
        for d0 in range(0, sc.T, 24):
            for h in C.TOU_HOURS:
                if C.TOU_HOURS[h] in ("peak", "critical"): ax.axvspan(d0 + h, d0 + h + 1, color="#d62728", alpha=.06, lw=0)
    axes[0].legend(ncol=4, fontsize=8, loc="upper right")
    sch = mpc_schedule(sc, LAM, GL); soc = evaluate(sc, sch)["soc_series"]
    axes[2].plot(np.arange(sc.T + 1), soc / C.BATT_ENERGY_MWH * 100, color="#6a3d9a"); axes[2].set_ylabel("battery %"); axes[2].set_xlabel("hour (red shading = peak/critical tariff)")
    fig.tight_layout(); fig.savefig(figures / "schedule.png"); plt.close(fig)

    # ---------------------------------------------------------------- 9. connection limit / cost of cap
    print("9/10 grid-cap sweep")
    grid_start = len(RUNS)
    limits = C.GRID_IMPORT_LIMIT_SWEEP_MW if not quick else [10.0, GL, None]
    limits = list(dict.fromkeys(limits))
    if None not in limits:
        limits.append(None)
    for limit in limits:
        avg(["baseline", "MPC"], gl=limit)
    grid_runs = [dict(r) for r in RUNS[grid_start:]]
    caps = grid_cap_summary(grid_runs)
    caps.to_csv(results / "grid_cap.csv", index=False)
    section("9. Grid import limit: paired cost of the cap vs uncapped MPC", caps)
    md.append("Cap effects compare the same seed and battery with uncapped MPC. "
              "Realized rolling-horizon differences can be signed. Blank deltas are infeasible comparisons.\n")
    fig, axes = plt.subplots(1, 2, figsize=(10, 4))
    x = np.arange(len(caps))
    for ax, metric, label in zip(axes, ("cost_cny", "objective"), ("cost", "objective")):
        delta = caps[f"{metric}_delta_vs_uncapped"].to_numpy(float) / 1000
        lo = caps[f"{metric}_delta_ci_low"].to_numpy(float) / 1000
        hi = caps[f"{metric}_delta_ci_high"].to_numpy(float) / 1000
        valid = np.isfinite(delta)
        ax.errorbar(x[valid], delta[valid], yerr=[delta[valid]-lo[valid], hi[valid]-delta[valid]],
                    fmt="o", capsize=4, color=COL["MPC"])
        for i in x[~valid]:
            ax.text(i, .02, "infeasible", transform=ax.get_xaxis_transform(), ha="center", fontsize=8, rotation=90)
        ax.axhline(0, color="#888888", lw=1)
        ax.set_xlim(-.5, len(caps)-.5)
        ax.set_xticks(x, caps.grid_limit_label, rotation=30, ha="right")
        ax.set(ylabel=f"{label} change vs uncapped (k CNY / block)", xlabel="grid import limit",
               title="Paired mean and 95% interval")
    fig.tight_layout(); fig.savefig(figures / "grid_cap.png"); plt.close(fig)

    # ---------------------------------------------------------------- 10. illustrative investment and billing assumptions
    print("10/10 battery and demand-charge economics")
    settings = dict(energy_costs=C.BATT_INSTALLED_COST_SWEEP_CNY_PER_KWH,
                    base_energy_cost=C.BATT_INSTALLED_COST_SWEEP_CNY_PER_KWH[len(C.BATT_INSTALLED_COST_SWEEP_CNY_PER_KWH)//2],
                    power_cost=C.BATT_INSTALLED_POWER_COST_CNY_PER_KW,
                    years=C.BATT_ECONOMIC_LIFE_YEARS, discount=C.ECON_DISCOUNT_RATE,
                    fixed_om=C.BATT_FIXED_OM_FRACTION_PER_YEAR,
                    demand_rates=C.DEMAND_CHARGE_SWEEP_CNY_PER_KW_MONTH,
                    annual_hours=C.ECON_HOURS_PER_YEAR)
    grid_econ, battery_econ, econ_runs = economics_tables(grid_runs, battery_runs, settings)
    grid_econ.to_csv(results / "grid_cap_economics.csv", index=False)
    battery_econ.to_csv(results / "battery_economics.csv", index=False)
    econ_runs.to_csv(results / "economics_runs.csv", index=False)
    md.append("\n## 10. Illustrative battery investment and demand billing\n")
    md.append(f"ASSUMPTIONS, not vendor quotes or applicable tariffs: installed energy costs "
              f"{settings['energy_costs']} CNY/kWh; power adder {settings['power_cost']} CNY/kW; "
              f"life {settings['years']} years; discount {settings['discount']:.1%}; fixed O&M "
              f"{settings['fixed_om']:.1%} of capex/year; demand rates {settings['demand_rates']} "
              f"CNY/kW/month. Annualization repeats each synthetic block to {settings['annual_hours']:g} hours. "
              "Its peak is only a monthly-peak proxy, not a measured yearly peak.\n")
    md.append("Capacity and measured-peak billing are alternatives, never added together. "
              "Capital recovery and fixed maintenance are included; throughput degradation is already "
              "in operating cost. Battery value is incremental to zero-battery MPC job shifting, not "
              "the no-scheduling baseline. NPV excludes carbon credits, tax, subsidy and salvage. "
              "Dispatch still optimizes the original energy/carbon objective: these are post-dispatch "
              "economic screens, not a demand-charge-optimal dispatch or bankable investment recommendation. "
              "Only all-seed feasible cases receive economic rankings. An uncapped contract has no "
              "defined capacity charge at a positive rate. Best means best among tested feasible caps only.\n")
    md.append("\n### Grid cap: annual costs including illustrative billing\n")
    md.append(grid_econ.round(2).to_markdown(index=False) + "\n")
